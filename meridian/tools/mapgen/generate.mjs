// Generates the world map and country table for the Meridian UI from
// Natural Earth data (public domain, via the world-atlas package).
//
//   cd tools/mapgen && npm install && npm run build
//
// Outputs:
//   internal/ui/web/js/worldmap.js   SVG paths keyed by ISO country code
//   internal/regions/countries.json  code, name, map position, lat/lon
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';
import { presimplify, simplify, quantile } from 'topojson-simplify';
import { geoEqualEarth, geoPath, geoCentroid, geoArea } from 'd3-geo';

const require = createRequire(import.meta.url);
const countries = require('i18n-iso-countries');
countries.registerLocale(require('i18n-iso-countries/langs/en.json'));
const topo = JSON.parse(fs.readFileSync(require.resolve('world-atlas/countries-50m.json'), 'utf8'));

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..');
const WIDTH = 1000;
const HEIGHT = 470;

// Keep enough detail for coastlines at UI size while staying small.
const pre = presimplify(topo);
const simple = simplify(pre, quantile(pre, 0.22));
const geo = feature(simple, simple.objects.countries);

// Antarctica takes space and never hosts a VPN server.
const features = geo.features.filter((f) => f.id !== '010');
const projection = geoEqualEarth().fitExtent([[6, 6], [WIDTH - 6, HEIGHT - 6]], { type: 'FeatureCollection', features });
const pathGen = geoPath(projection);
const k = projection.scale();
const [tx, ty] = projection.translate();

const special = { Kosovo: 'XK', 'N. Cyprus': 'CY', Somaliland: 'SO' };

function round(d) {
  return d.replace(/-?\d+\.\d+/g, (n) => (Math.round(parseFloat(n) * 10) / 10).toString());
}

// Centroid of the largest polygon, so France's pin sits in France rather
// than in the Atlantic between it and French Guiana.
function mainCentroid(f) {
  if (f.geometry.type !== 'MultiPolygon') return geoCentroid(f);
  let best = null;
  let bestArea = -1;
  for (const coords of f.geometry.coordinates) {
    const poly = { type: 'Feature', geometry: { type: 'Polygon', coordinates: coords } };
    const a = geoArea(poly);
    if (a > bestArea) {
      bestArea = a;
      best = poly;
    }
  }
  return geoCentroid(best);
}

const shapes = [];
const positions = {};
for (const f of features) {
  let code = f.id ? countries.numericToAlpha2(f.id) : undefined;
  if (!code) code = special[f.properties.name];
  const d = pathGen(f);
  if (!d) continue;
  shapes.push({ c: code || '', d: round(d) });
  if (code && !positions[code]) {
    const [lon, lat] = mainCentroid(f);
    const [x, y] = projection([lon, lat]);
    positions[code] = { lat: +lat.toFixed(2), lon: +lon.toFixed(2), x: +x.toFixed(1), y: +y.toFixed(1) };
  }
}

// Short names people expect in a location list.
const shortNames = {
  US: 'United States', GB: 'United Kingdom', RU: 'Russia', KR: 'South Korea', KP: 'North Korea',
  IR: 'Iran', SY: 'Syria', VN: 'Vietnam', LA: 'Laos', BO: 'Bolivia', VE: 'Venezuela', TZ: 'Tanzania',
  MD: 'Moldova', CZ: 'Czechia', TW: 'Taiwan', HK: 'Hong Kong', MO: 'Macau', BN: 'Brunei',
  PS: 'Palestine', CD: 'DR Congo', CG: 'Congo', FM: 'Micronesia', VA: 'Vatican City', XK: 'Kosovo',
  MK: 'North Macedonia', CI: "Côte d'Ivoire", AE: 'United Arab Emirates', BA: 'Bosnia and Herzegovina',
};

const table = [];
for (const code of Object.keys(countries.getAlpha2Codes()).concat(['XK'])) {
  const name = shortNames[code] || countries.getName(code, 'en', { select: 'official' }) || code;
  table.push({ code, name, ...(positions[code] || {}) });
}
table.sort((a, b) => a.name.localeCompare(b.name));

const mapJS = `// Generated by tools/mapgen/generate.mjs from Natural Earth data (public domain).
// Do not edit by hand.
export const MAP = ${JSON.stringify({ width: WIDTH, height: HEIGHT, k: +k.toFixed(4), tx: +tx.toFixed(3), ty: +ty.toFixed(3), shapes })};
`;
fs.writeFileSync(path.join(root, 'internal/ui/web/js/worldmap.js'), mapJS);
fs.writeFileSync(path.join(root, 'internal/regions/countries.json'), JSON.stringify(table, null, 0).replace(/\},\{/g, '},\n{') + '\n');
console.log(`map: ${shapes.length} shapes, ${(mapJS.length / 1024).toFixed(0)} KB; countries: ${table.length} (${Object.keys(positions).length} on map)`);
